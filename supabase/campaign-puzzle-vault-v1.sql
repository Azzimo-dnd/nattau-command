-- Build the initial public run state from a puzzle's public configuration.
create or replace function public.build_campaign_puzzle_initial_state(
  p_type text,
  p_public_config jsonb
)
returns jsonb
language plpgsql
immutable
set search_path = public
as $$
begin
  case p_type
    when 'rune_cipher' then
      return jsonb_build_object('guesses', '[]'::jsonb);
    when 'sliding_lock' then
      return jsonb_build_object('blocks', coalesce(p_public_config->'blocks', '[]'::jsonb), 'selected', null);
    when 'shattered_sigil' then
      return jsonb_build_object('order', coalesce(p_public_config->'initial_order', '[]'::jsonb), 'selected', null);
    when 'arcane_circuit' then
      return jsonb_build_object('rotations', coalesce(p_public_config->'initial_rotations', '[]'::jsonb));
    when 'rune_sequence' then
      return jsonb_build_object('level', 1, 'last_feedback', null, 'reveals', 0);
    else
      raise exception 'Unsupported puzzle type: %', p_type;
  end case;
end;
$$;

-- Rotate a N/E/S/W bit mask clockwise. Used server-side so symmetric
-- circuit pieces (for example a straight line rotated 180°) count as solved.
create or replace function public.rotate_campaign_puzzle_mask(
  p_mask integer,
  p_rotation integer
)
returns integer
language plpgsql
immutable
set search_path = public
as $$
declare
  v_value integer := p_mask;
  v_steps integer := ((coalesce(p_rotation,0) % 4) + 4) % 4;
  v_n integer;
  v_e integer;
  v_s integer;
  v_w integer;
  i integer;
begin
  if v_steps > 0 then
    for i in 1..v_steps loop
      v_n := v_value & 1;
      v_e := v_value & 2;
      v_s := v_value & 4;
      v_w := v_value & 8;
      v_value := (case when v_n <> 0 then 2 else 0 end)
               | (case when v_e <> 0 then 4 else 0 end)
               | (case when v_s <> 0 then 8 else 0 end)
               | (case when v_w <> 0 then 1 else 0 end);
    end loop;
  end if;
  return v_value;
end;
$$;

-- DM-only create/update. Secret config is kept in a separate RLS-protected table.
create or replace function public.save_campaign_puzzle(
  p_campaign_slug text,
  p_puzzle_id uuid,
  p_payload jsonb
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_campaign_id uuid;
  v_puzzle_id uuid;
  v_type text;
  v_title text;
  v_description text;
  v_difficulty text;
  v_move_limit integer;
  v_attempt_limit integer;
  v_time_limit integer;
  v_failure_message text;
  v_public_config jsonb;
  v_secret_config jsonb;
  v_sort_order integer;
begin
  select c.id into v_campaign_id
  from public.campaigns c
  where c.slug = lower(trim(p_campaign_slug)) and c.is_active = true;

  if v_campaign_id is null then
    raise exception 'Campaign not found or inactive.';
  end if;
  if not public.is_campaign_dm(v_campaign_id) then
    raise exception 'Only the campaign Game Master may configure puzzles.';
  end if;

  v_type := trim(coalesce(p_payload->>'puzzle_type', ''));
  v_title := trim(coalesce(p_payload->>'title', ''));
  v_description := coalesce(p_payload->>'description', '');
  v_difficulty := trim(coalesce(p_payload->>'difficulty_label', 'Medium'));
  v_move_limit := nullif(p_payload->>'move_limit', '')::integer;
  v_attempt_limit := nullif(p_payload->>'attempt_limit', '')::integer;
  v_time_limit := nullif(p_payload->>'time_limit_seconds', '')::integer;
  v_failure_message := nullif(p_payload->>'failure_message', '');
  v_public_config := coalesce(p_payload->'public_config', '{}'::jsonb);
  v_secret_config := coalesce(p_payload->'secret_config', '{}'::jsonb);
  v_sort_order := coalesce((p_payload->>'sort_order')::integer, 500);

  if v_type not in ('rune_cipher','sliding_lock','shattered_sigil','arcane_circuit','rune_sequence') then
    raise exception 'Unsupported puzzle type.';
  end if;
  if char_length(v_title) < 1 or char_length(v_title) > 120 then
    raise exception 'Puzzle title must contain 1-120 characters.';
  end if;
  if char_length(v_description) > 2000 then
    raise exception 'Puzzle description is too long.';
  end if;
  if v_move_limit is not null and (v_move_limit < 1 or v_move_limit > 999) then
    raise exception 'Move limit must be between 1 and 999.';
  end if;
  if v_attempt_limit is not null and (v_attempt_limit < 1 or v_attempt_limit > 999) then
    raise exception 'Attempt limit must be between 1 and 999.';
  end if;
  if v_time_limit is not null and (v_time_limit < 10 or v_time_limit > 86400) then
    raise exception 'Time limit must be between 10 and 86400 seconds.';
  end if;

  if p_puzzle_id is null then
    insert into public.campaign_puzzles (
      campaign_id, title, description, puzzle_type, difficulty_label,
      public_config, move_limit, attempt_limit, time_limit_seconds,
      failure_message, is_visible, status, sort_order, created_by, updated_by
    ) values (
      v_campaign_id, v_title, v_description, v_type, v_difficulty,
      v_public_config, v_move_limit, v_attempt_limit, v_time_limit,
      v_failure_message, false, 'draft', v_sort_order, auth.uid(), auth.uid()
    ) returning id into v_puzzle_id;
  else
    if not exists (
      select 1 from public.campaign_puzzles p
      where p.id = p_puzzle_id and p.campaign_id = v_campaign_id
    ) then
      raise exception 'Puzzle not found in this campaign.';
    end if;
    v_puzzle_id := p_puzzle_id;
    update public.campaign_puzzles
    set title = v_title,
        description = v_description,
        puzzle_type = v_type,
        difficulty_label = v_difficulty,
        public_config = v_public_config,
        move_limit = v_move_limit,
        attempt_limit = v_attempt_limit,
        time_limit_seconds = v_time_limit,
        failure_message = v_failure_message,
        sort_order = v_sort_order,
        updated_by = auth.uid()
    where id = v_puzzle_id;
  end if;

  insert into public.campaign_puzzle_secrets (
    puzzle_id, campaign_id, secret_config, updated_by, updated_at
  ) values (
    v_puzzle_id, v_campaign_id, v_secret_config, auth.uid(), now()
  )
  on conflict (puzzle_id) do update
  set secret_config = excluded.secret_config,
      updated_by = excluded.updated_by,
      updated_at = now();

  return v_puzzle_id;
end;
$$;

create or replace function public.start_campaign_puzzle(
  p_puzzle_id uuid,
  p_make_visible boolean default true
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_puzzle public.campaign_puzzles%rowtype;
  v_run_id uuid;
  v_state jsonb;
  v_deadline timestamptz;
begin
  select * into v_puzzle
  from public.campaign_puzzles
  where id = p_puzzle_id
  for update;

  if v_puzzle.id is null then raise exception 'Puzzle not found.'; end if;
  if not public.is_campaign_dm(v_puzzle.campaign_id) then
    raise exception 'Only the campaign Game Master may start puzzles.';
  end if;
  if v_puzzle.status = 'archived' then
    raise exception 'Archived puzzles cannot be started.';
  end if;

  if v_puzzle.current_run_id is not null then
    update public.campaign_puzzle_runs
    set status = case when status = 'active' then 'superseded' else status end,
        controller_user_id = null,
        controller_name = null,
        control_expires_at = null,
        updated_at = now()
    where id = v_puzzle.current_run_id;
  end if;

  v_state := public.build_campaign_puzzle_initial_state(v_puzzle.puzzle_type, v_puzzle.public_config);
  v_deadline := case
    when v_puzzle.time_limit_seconds is null then null
    else now() + make_interval(secs => v_puzzle.time_limit_seconds)
  end;

  insert into public.campaign_puzzle_runs (
    puzzle_id, campaign_id, status, state, move_count, attempt_count,
    started_at, deadline_at, version, updated_at
  ) values (
    v_puzzle.id, v_puzzle.campaign_id, 'active', v_state, 0, 0,
    now(), v_deadline, 1, now()
  ) returning id into v_run_id;

  update public.campaign_puzzles
  set current_run_id = v_run_id,
      status = 'active',
      is_visible = p_make_visible,
      updated_by = auth.uid()
  where id = v_puzzle.id;

  return v_run_id;
end;
$$;


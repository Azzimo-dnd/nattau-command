create or replace function public.take_campaign_puzzle_control(p_run_id uuid)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_run public.campaign_puzzle_runs%rowtype;
  v_name text;
  v_is_dm boolean;
begin
  if auth.uid() is null then raise exception 'Authentication required.'; end if;

  select * into v_run from public.campaign_puzzle_runs where id=p_run_id for update;
  if v_run.id is null then raise exception 'Puzzle run not found.'; end if;
  if not public.can_view_campaign_puzzle(v_run.puzzle_id) then raise exception 'Puzzle access denied.'; end if;
  if v_run.status <> 'active' then return false; end if;

  v_is_dm := public.is_campaign_dm(v_run.campaign_id);
  if v_run.controller_user_id is not null
     and v_run.controller_user_id <> auth.uid()
     and coalesce(v_run.control_expires_at, '-infinity'::timestamptz) > now()
     and not v_is_dm then
    return false;
  end if;

  select nullif(trim(p.display_name),'') into v_name
  from public.profiles p where p.id=auth.uid();

  update public.campaign_puzzle_runs
  set controller_user_id=auth.uid(),
      controller_name=coalesce(v_name,'Campaign member'),
      control_expires_at=now()+interval '45 seconds',
      updated_at=now()
  where id=p_run_id;
  return true;
end;
$$;


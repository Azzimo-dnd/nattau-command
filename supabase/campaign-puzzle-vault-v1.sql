create or replace function public.can_access_campaign_puzzle_topic(target_topic text)
returns boolean
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_run_id uuid;
  v_puzzle_id uuid;
begin
  if target_topic is null or target_topic !~ '^campaign-puzzle:[0-9a-fA-F-]{36}$' then
    return false;
  end if;

  begin
    v_run_id := split_part(target_topic, ':', 2)::uuid;
  exception when others then
    return false;
  end;

  select r.puzzle_id into v_puzzle_id
  from public.campaign_puzzle_runs r
  where r.id = v_run_id;

  if v_puzzle_id is null then
    return false;
  end if;

  return public.can_view_campaign_puzzle(v_puzzle_id);
end;
$$;


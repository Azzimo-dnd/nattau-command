begin;

create table if not exists public.campaign_puzzles (
  id uuid primary key default gen_random_uuid(),
  campaign_id uuid not null references public.campaigns(id) on delete cascade,
  title text not null,
  description text not null default '',
  puzzle_type text not null,
  difficulty_label text not null default 'Medium',
  public_config jsonb not null default '{}'::jsonb,
  move_limit integer,
  attempt_limit integer,
  time_limit_seconds integer,
  failure_message text,
  is_visible boolean not null default false,
  status text not null default 'draft',
  current_run_id uuid,
  sort_order integer not null default 500,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint campaign_puzzles_type_check check (
    puzzle_type in ('rune_cipher','sliding_lock','shattered_sigil','arcane_circuit','rune_sequence')
  ),
  constraint campaign_puzzles_status_check check (
    status in ('draft','active','solved','failed','archived')
  ),
  constraint campaign_puzzles_title_check check (char_length(trim(title)) between 1 and 120),
  constraint campaign_puzzles_description_check check (char_length(description) <= 2000),
  constraint campaign_puzzles_failure_message_check check (failure_message is null or char_length(failure_message) <= 500),
  constraint campaign_puzzles_move_limit_check check (move_limit is null or move_limit between 1 and 999),
  constraint campaign_puzzles_attempt_limit_check check (attempt_limit is null or attempt_limit between 1 and 999),
  constraint campaign_puzzles_time_limit_check check (time_limit_seconds is null or time_limit_seconds between 10 and 86400)
);

create table if not exists public.campaign_puzzle_secrets (
  puzzle_id uuid primary key references public.campaign_puzzles(id) on delete cascade,
  campaign_id uuid not null references public.campaigns(id) on delete cascade,
  secret_config jsonb not null default '{}'::jsonb,
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);

create table if not exists public.campaign_puzzle_runs (
  id uuid primary key default gen_random_uuid(),
  puzzle_id uuid not null references public.campaign_puzzles(id) on delete cascade,
  campaign_id uuid not null references public.campaigns(id) on delete cascade,
  status text not null default 'active',
  state jsonb not null default '{}'::jsonb,
  move_count integer not null default 0,
  attempt_count integer not null default 0,
  started_at timestamptz not null default now(),
  deadline_at timestamptz,
  solved_at timestamptz,
  failed_at timestamptz,
  controller_user_id uuid references auth.users(id) on delete set null,
  controller_name text,
  control_expires_at timestamptz,
  version integer not null default 1,
  updated_at timestamptz not null default now(),
  constraint campaign_puzzle_runs_status_check check (
    status in ('active','solved','failed','superseded')
  ),
  constraint campaign_puzzle_runs_counts_check check (move_count >= 0 and attempt_count >= 0)
);

create table if not exists public.campaign_puzzle_moves (
  id bigint generated by default as identity primary key,
  run_id uuid not null references public.campaign_puzzle_runs(id) on delete cascade,
  puzzle_id uuid not null references public.campaign_puzzles(id) on delete cascade,
  campaign_id uuid not null references public.campaigns(id) on delete cascade,
  actor_id uuid not null references auth.users(id) on delete cascade,
  move_number integer not null,
  action jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  unique (run_id, move_number)
);

create index if not exists campaign_puzzles_campaign_idx
  on public.campaign_puzzles(campaign_id, status, is_visible, sort_order);
create index if not exists campaign_puzzle_runs_campaign_idx
  on public.campaign_puzzle_runs(campaign_id, puzzle_id, started_at desc);
create index if not exists campaign_puzzle_moves_run_idx
  on public.campaign_puzzle_moves(run_id, move_number);

